import type { ContentLoading } from './content-loading.js';
import type { SignInPort } from '../session/sign-ins.js';
import type { CodePort } from '../session/codes.js';
import type { ApprovalReview } from '../features/approvals/review.js';
import type { ChatDelivery } from '../features/chat/delivery.js';
import type { AppState, ArtifactFormat, Command, CommandResult, DeepReadonly, ProtocolAdapter } from '../protocol/models.js';
import type { ArtifactDock } from '../components/dock.js';
import type { DialogManager } from '../components/dialog.js';
export type Route = 'chat' | 'search' | 'feed' | 'ideas' | 'goals' | 'library' | 'browser' | 'memory' | 'schedule' | 'notifications' | 'published';
export type LibraryFilter = 'all' | 'documents' | 'web' | 'images' | 'videos' | 'audio' | 'system' | 'trash';
export type ContextTab = 'activity' | 'approvals' | 'schedule' | 'identity';
export interface UiState {
    sideChatsOpen: boolean;
    connectorChatsOpen: boolean;
    fileImports: Map<string, {
        id: string;
        chatId: string;
        file: File;
        phase: 'reading' | 'failed';
        error: string;
    }>;
    preparingChats: Set<string>;
    navigationWidth: number;
    route: Route;
    chatId: string;
    libraryFilter: LibraryFilter;
    search: string;
    navSearch: string;
    draft: string;
    navOpen: boolean;
    pageNavOpen: boolean;
    lastMotionRoute: Route | null;
    contextOpen: boolean;
    contextTab: ContextTab;
    contextScroll: Map<ContextTab, number>;
    recentChatIds: string[];
    libraryLayout: 'grid' | 'list';
    librarySort: 'opened' | 'created' | 'title';
    selectionMode: boolean;
    selectedArtifacts: Set<string>;
    goalFilter: 'active' | 'closed';
    goalExamples: boolean;
    ideaExamples: boolean;
    feedPromptOpen: boolean;
    systemSort: 'asc' | 'desc';
    ideaFilter: 'suggested' | 'active' | 'dismissed';
    memoryFilter: 'profile' | 'people' | 'memory' | 'preferences' | 'logs';
    scheduleFilter: 'all' | 'time' | 'hook';
    showArchived: boolean;
    attachmentNames: string[];
    systemFolder: string;
    systemExpanded: Set<string>;
    systemSelected: string;
    publicationId: string;
}
export interface AppContext {
    readonly adapter: ProtocolAdapter;
    /** Where a sign-in to keep goes, when the app is connected to Hatchling (WO-030). */
    readonly signIns: SignInPort | undefined;
    /** Where a one-time code goes, when the app is connected to Hatchling (WO-030). */
    readonly codes: CodePort | undefined;
    readonly delivery: ChatDelivery;
    readonly contentLoading: ContentLoading;
    readonly approvals: ApprovalReview;
    readonly state: DeepReadonly<AppState>;
    readonly ui: UiState;
    readonly dialogs: DialogManager;
    readonly dock: ArtifactDock;
    render(): void;
    navigate(route: Route, detail?: string): void;
    run(command: Command, silent?: boolean): Promise<CommandResult>;
    toast(message: string, error?: boolean): void;
    openSettings(tab?: string): void;
    openArtifact(id: string): void;
    openMemoryDocument(id: string): void;
    openThread(id: string): void;
    openBrowser(id: string): void;
    prefillComposer(text: string): void;
    saveComposer(): void;
    completeQueuedDraft(chatId: string, text: string, attachments: readonly string[]): void;
    stageAttachment(chatId: string, id: string): void;
    recoverComposer(chatId: string, text: string, attachments: readonly string[]): void;
    openScenarios(): void;
    openSearch(): void;
    createArtifact(format?: ArtifactFormat): void;
}
