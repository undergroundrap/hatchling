    def test_50_timeline_selection_keyboard_and_independent_scroll_survive_reopen(self):
        self.page.set_viewport_size({'width': 1174, 'height': 650})
        dialog = self.rich_activity()
        nav = dialog.locator('.activity-timeline')
        report = dialog.locator('.activity-report-pane')
        report.evaluate('(el) => el.scrollTop = 200')
        self.page.wait_for_timeout(40)
        report_top = report.evaluate('(el) => el.scrollTop')
        nav.evaluate('(el) => el.scrollTop = 120')
        self.page.wait_for_timeout(40)
        self.assertAlmostEqual(report.evaluate('(el) => el.scrollTop'), report_top, delta=2)
        self.page.keyboard.press('Escape')
        dialog = self.rich_activity()
        self.assertAlmostEqual(dialog.locator('.activity-timeline').evaluate('(el) => el.scrollTop'), 120, delta=2)
        self.assertAlmostEqual(dialog.locator('.activity-report-pane').evaluate('(el) => el.scrollTop'), report_top, delta=2)
        dialog.locator('#timeline-summary').focus()
        self.page.keyboard.press('ArrowDown')
        expect(dialog.locator('#timeline-dynamic-start')).to_have_attribute('aria-pressed', 'true')
        expect(dialog.locator('#timeline-dynamic-start')).to_be_focused()
        self.page.keyboard.press('End')
        expect(dialog.locator('#timeline-dynamic-finish')).to_be_focused()
        expect(dialog.locator('.activity-report-pane > h3')).to_have_text('Completed Document Structure Review')

