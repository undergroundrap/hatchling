    def test_60_lottie_player_stops_on_preference_change_and_after_navigation(self):
        self.page.emulate_media(reduced_motion='no-preference')
        self.page.locator('#rail-feed').hover()
        glyph = self.page.locator('#rail-feed .lottie-glyph')
        expect(glyph).to_have_class(re.compile('icon-playing'))
        self.page.wait_for_timeout(90)
        first_frame = float(glyph.get_attribute('data-frame'))
        self.page.wait_for_timeout(90)
        self.assertGreater(float(glyph.get_attribute('data-frame')), first_frame)
        self.page.emulate_media(reduced_motion='reduce')
        expect(glyph).not_to_have_class(re.compile('icon-playing'))
        self.assertEqual(float(glyph.get_attribute('data-frame')), 64)
        for route in ['goals', 'feed', 'ideas', 'chat']:
            self.route(route)
            expect(self.page.locator('.icon-rail .lottie-glyph')).to_have_count(6)
        expect(self.page.locator('.icon-rail .icon-playing')).to_have_count(0)

