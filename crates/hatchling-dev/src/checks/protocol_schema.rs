//! The frontend protocol schema, generated from
//! hatchling-core's wire types.
//!
//! The Rust types are the one source: `hatchling-core`'s `schema`
//! feature derives a JSON Schema for each, and [`generate`] collects
//! the session protocol's and the UI protocol's root types into one
//! draft 2020-12 document, written to [`SCHEMA_PATH`]. The frontend
//! generates its TypeScript types from that file
//! (`frontend/scripts/generate-protocol.mjs`).
//!
//! `hatchling-dev protocol-schema` checks that the checked-in file is
//! current and names it if it is not; `--write` regenerates it. Output
//! is canonical: object keys sorted, two-space indent, one trailing
//! newline, so the same types always give the same bytes, and the
//! frontend's formatter (`JSON.stringify(value, null, 2)`) leaves the
//! file as it is.

use std::path::Path;

use hatchling_core::PROTOCOL_VERSION;
use hatchling_core::messages::{
    AgentMessage, BrokerMessage, DeviceChallenge, DeviceHello, DeviceRefusal, DeviceWelcome,
    SessionRequest, SessionResponse,
};
use hatchling_core::subagent::ActivityEvent;
use hatchling_core::ui::operator::{OperatorRequest, OperatorResponse};
use hatchling_core::ui::{
    BACKEND_NEWER, Control, FRONTEND_NEWER, UI_SCHEMA_VERSION, UiRequest, UiResponse, control,
};
use schemars::generate::SchemaSettings;
use serde_json::{Map, Value, json};

use super::Finding;
use crate::Error;

/// The finding tag.
pub const CHECK: &str = "protocol-schema";

/// Where the schema lives, relative to the workspace root.
pub const SCHEMA_PATH: &str = "frontend/protocol/schema.json";

/// The schema document, canonical.
#[must_use]
pub fn generate() -> String {
    let mut generator = SchemaSettings::draft2020_12().into_generator();
    let mut roots = Map::new();
    let mut root = |name: &str, schema: schemars::Schema| {
        roots.insert(name.to_owned(), schema.to_value());
    };
    root("UiRequest", generator.subschema_for::<UiRequest>());
    root("UiResponse", generator.subschema_for::<UiResponse>());
    root(
        "OperatorRequest",
        generator.subschema_for::<OperatorRequest>(),
    );
    root(
        "OperatorResponse",
        generator.subschema_for::<OperatorResponse>(),
    );
    root("ActivityEvent", generator.subschema_for::<ActivityEvent>());
    root(
        "SessionRequest",
        generator.subschema_for::<SessionRequest>(),
    );
    root(
        "SessionResponse",
        generator.subschema_for::<SessionResponse>(),
    );
    root("AgentMessage", generator.subschema_for::<AgentMessage>());
    root("BrokerMessage", generator.subschema_for::<BrokerMessage>());
    root("DeviceHello", generator.subschema_for::<DeviceHello>());
    root(
        "DeviceChallenge",
        generator.subschema_for::<DeviceChallenge>(),
    );
    root("DeviceWelcome", generator.subschema_for::<DeviceWelcome>());
    root("DeviceRefusal", generator.subschema_for::<DeviceRefusal>());
    // The takeover table's states: no frame carries them, since
    // control moves only by handoffs, but the table is part of the contract.
    root("Control", generator.subschema_for::<Control>());
    let definitions = generator.take_definitions(true);
    let document = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://hatchling.invalid/protocol/schema.json",
        "title": "Hatchling frontend protocol",
        "description": "Generated by `hatchling-dev protocol-schema --write` from hatchling-core's wire types. Do not edit.",
        "x-hatchling": {
            "ui_schema_version": UI_SCHEMA_VERSION,
            "session_protocol": PROTOCOL_VERSION,
            "incompatible": {
                "frontend_newer": FRONTEND_NEWER,
                "backend_newer": BACKEND_NEWER,
            },
            "control": {
                "transitions": control::transitions()
                    .into_iter()
                    .map(|(from, handoff, to)| json!({"from": from, "handoff": handoff, "to": to}))
                    .collect::<Vec<_>>(),
            },
        },
        "x-roots": Value::Object(roots),
        "$defs": Value::Object(definitions),
    });
    render(&document)
}

/// `value` with every object's keys sorted, pretty-printed with a
/// trailing newline.
fn render(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(&canonical(value)).unwrap_or_default();
    text.push('\n');
    text
}

/// `value` with every object's keys sorted, recursively.
fn canonical(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let mut sorted = Map::new();
            for key in keys {
                if let Some(inner) = map.get(key) {
                    sorted.insert(key.clone(), canonical(inner));
                }
            }
            Value::Object(sorted)
        }
        Value::Array(items) => Value::Array(items.iter().map(canonical).collect()),
        Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => value.clone(),
    }
}

/// Check (or with `write`, rewrite) the schema under `root`.
///
/// # Errors
///
/// Returns [`Error::Io`] if the schema cannot be read (other than
/// being missing) or written.
pub fn run(root: &Path, write: bool) -> Result<Vec<Finding>, Error> {
    let path = root.join(SCHEMA_PATH);
    let current = generate();
    if write {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(Error::Io)?;
        }
        std::fs::write(&path, current).map_err(Error::Io)?;
        return Ok(Vec::new());
    }
    let checked_in = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            return Ok(vec![Finding::new(
                CHECK,
                format!(
                    "{SCHEMA_PATH} is missing: run `cargo run -p hatchling-dev -- protocol-schema --write`"
                ),
            )]);
        }
        Err(error) => return Err(Error::Io(error)),
    };
    if checked_in == current {
        Ok(Vec::new())
    } else {
        Ok(vec![Finding::new(
            CHECK,
            format!(
                "{SCHEMA_PATH} is out of date with hatchling-core's wire types: run `cargo run -p hatchling-dev -- protocol-schema --write`, then `npm run protocol:generate` in frontend/"
            ),
        )])
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;
    use crate::workspace_root;

    fn document() -> Value {
        serde_json::from_str(&generate()).unwrap()
    }

    #[test]
    fn the_checked_in_schema_is_current() {
        let path = workspace_root().join(SCHEMA_PATH);
        let checked_in = std::fs::read_to_string(&path).unwrap();
        assert!(
            checked_in == generate(),
            "{SCHEMA_PATH} is stale: run `cargo run -p hatchling-dev -- protocol-schema --write`"
        );
    }

    #[test]
    fn generation_is_deterministic_and_canonical() {
        let text = generate();
        assert_eq!(text, generate());
        assert!(text.ends_with("}\n") && !text.ends_with("\n\n"));
        let reparsed: Value = serde_json::from_str(&text).unwrap();
        assert_eq!(render(&reparsed), text, "rendering is a fixed point");
        assert!(text.contains("\n  \"$defs\": {"), "two-space indent");
    }

    #[test]
    fn canonical_sorts_every_object_at_every_depth() {
        let unsorted = json!({"b": [{"z": 1, "a": null}], "a": {"y": true, "c": "s"}});
        let sorted = canonical(&unsorted);
        assert_eq!(
            serde_json::to_string(&sorted).unwrap(),
            r#"{"a":{"c":"s","y":true},"b":[{"a":null,"z":1}]}"#
        );
        assert_eq!(render(&json!({"k": 1})), "{\n  \"k\": 1\n}\n");
    }

    #[test]
    fn the_document_names_its_versions_and_mismatch_sentences() {
        let doc = document();
        assert_eq!(
            doc.pointer("/x-hatchling/ui_schema_version").unwrap(),
            &json!(UI_SCHEMA_VERSION)
        );
        assert_eq!(
            doc.pointer("/x-hatchling/session_protocol").unwrap(),
            &json!(PROTOCOL_VERSION)
        );
        assert_eq!(
            doc.pointer("/x-hatchling/incompatible/frontend_newer")
                .unwrap(),
            &json!(FRONTEND_NEWER)
        );
        assert_eq!(
            doc.pointer("/x-hatchling/incompatible/backend_newer")
                .unwrap(),
            &json!(BACKEND_NEWER)
        );
        assert_eq!(
            doc.pointer("/x-hatchling/control/transitions/0").unwrap(),
            &json!({"from": "agent", "handoff": "takeover", "to": "to_user"})
        );
        assert_eq!(
            doc.pointer("/x-hatchling/control/transitions")
                .and_then(Value::as_array)
                .map(Vec::len),
            Some(control::transitions().len()),
            "the whole takeover table, from hatchling-core"
        );
        assert_eq!(
            doc.pointer("/$schema").unwrap(),
            &json!("https://json-schema.org/draft/2020-12/schema")
        );
    }

    #[test]
    fn every_root_and_every_reference_resolves() {
        let doc = document();
        let defs = doc.pointer("/$defs").unwrap().as_object().unwrap();
        let roots = doc.pointer("/x-roots").unwrap().as_object().unwrap();
        let names: BTreeSet<&str> = roots.keys().map(String::as_str).collect();
        let expected: BTreeSet<&str> = [
            "ActivityEvent",
            "AgentMessage",
            "BrokerMessage",
            "Control",
            "DeviceChallenge",
            "DeviceHello",
            "DeviceRefusal",
            "DeviceWelcome",
            "OperatorRequest",
            "OperatorResponse",
            "SessionRequest",
            "SessionResponse",
            "UiRequest",
            "UiResponse",
        ]
        .into();
        assert_eq!(names, expected);
        let mut refs = Vec::new();
        collect_refs(&doc, &mut refs);
        assert!(refs.len() > 100, "{} references", refs.len());
        for reference in refs {
            let name = reference.strip_prefix("#/$defs/").unwrap();
            assert!(defs.contains_key(name), "dangling {reference}");
        }
    }

    fn collect_refs(value: &Value, out: &mut Vec<String>) {
        match value {
            Value::Object(map) => {
                if let Some(Value::String(reference)) = map.get("$ref") {
                    out.push(reference.clone());
                }
                map.values().for_each(|inner| collect_refs(inner, out));
            }
            Value::Array(items) => items.iter().for_each(|inner| collect_refs(inner, out)),
            Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {}
        }
    }

    #[test]
    fn the_schema_covers_every_session_family_and_the_interrupted_state() {
        let text = generate();
        for family in [
            "vault", "egress", "channel", "memory", "skill", "goals", "query", "schedule", "hook",
            "artifact", "space", "subagent",
        ] {
            let tag = format!("\"const\": \"{family}\"");
            let keyed = format!("\"{family}\": {{");
            assert!(
                text.contains(&tag) || text.contains(&keyed),
                "session family {family}"
            );
        }
        let doc = document();
        let state = doc.pointer("/$defs/ActivityState").unwrap().to_string();
        for value in ["pending", "success", "partial", "failed", "interrupted"] {
            assert!(
                state.contains(&format!("\"{value}\"")),
                "{value} in {state}"
            );
        }
    }

    fn scratch(name: &str) -> std::path::PathBuf {
        // `/tmp` directly: under cargo-mutants `temp_dir()` follows
        // TMPDIR into the workspace's scratch copy.
        let dir = Path::new("/tmp").join(format!(
            "hatchling-dev-schema-{name}-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn run_names_a_missing_or_stale_schema_and_write_fixes_it() {
        let root = scratch("run");
        let missing = run(&root, false).unwrap();
        assert_eq!(missing.len(), 1);
        assert_eq!(missing.first().unwrap().check, CHECK);
        assert!(
            missing.first().unwrap().message.contains("is missing"),
            "{:?}",
            missing.first().unwrap()
        );
        assert!(run(&root, true).unwrap().is_empty());
        assert_eq!(
            std::fs::read_to_string(root.join(SCHEMA_PATH)).unwrap(),
            generate()
        );
        assert!(run(&root, false).unwrap().is_empty());
        std::fs::write(root.join(SCHEMA_PATH), "{}\n").unwrap();
        let stale = run(&root, false).unwrap();
        assert_eq!(stale.len(), 1);
        assert!(
            stale.first().unwrap().message.contains("out of date"),
            "{:?}",
            stale.first().unwrap()
        );
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn an_unreadable_schema_is_an_error_not_a_finding() {
        let root = scratch("unreadable");
        std::fs::create_dir_all(root.join(SCHEMA_PATH)).unwrap();
        assert!(
            run(&root, false).is_err(),
            "a directory where the file should be"
        );
        let _ = std::fs::remove_dir_all(&root);
    }
}
